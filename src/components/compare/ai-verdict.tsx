import { Minus, Plus, Sparkles } from "lucide-react";

import { getAiComparison } from "@/lib/ai/compare-cached";
import { swapComparison } from "@/lib/ai/swap";
import { cn } from "@/lib/utils";
import type { ProductWithSpecs } from "@/types/catalog";

export async function AiVerdict({ a, b }: { a: ProductWithSpecs; b: ProductWithSpecs }) {
  let result: Awaited<ReturnType<typeof getAiComparison>>;
  try {
    result = await getAiComparison(a.slug, b.slug);
  } catch (error) {
    console.error("AI comparison failed", error);
    return <VerdictShell>The AI summary is unavailable right now. The spec table below is still accurate.</VerdictShell>;
  }
  if (!result) {
    return <VerdictShell>AI summaries are not enabled on this server. Compare the specs below.</VerdictShell>;
  }

  const c = result.swapped ? swapComparison(result.comparison) : result.comparison;
  const names = { a: a.name, b: b.name, either: "Either" } as const;

  return (
    <section aria-labelledby="ai-verdict" className="rounded-3xl border border-border bg-card p-6 sm:p-8">
      <p id="ai-verdict" className="spec-figure flex items-center gap-2 text-[11px] uppercase tracking-[0.18em] text-primary">
        <Sparkles className="size-3.5" /> AI summary
      </p>
      <p className="mt-3 text-pretty text-xl font-semibold leading-snug sm:text-2xl">{c.headline}</p>

      <div className="mt-8 grid gap-6 md:grid-cols-2">
        {(["a", "b"] as const).map((key) => (
          <div key={key}>
            <h3 className="font-semibold">{names[key]}</h3>
            <ul className="mt-3 space-y-2 text-sm">
              {c[key].strengths.map((s) => (
                <li key={s} className="flex gap-2">
                  <Plus className="mt-0.5 size-4 shrink-0 text-success" aria-label="Strength" />
                  {s}
                </li>
              ))}
              {c[key].tradeoffs.map((s) => (
                <li key={s} className="flex gap-2 text-muted-foreground">
                  <Minus className="mt-0.5 size-4 shrink-0 text-warning" aria-label="Trade-off" />
                  {s}
                </li>
              ))}
            </ul>
          </div>
        ))}
      </div>

      <h3 className="mt-8 text-xs font-semibold uppercase tracking-[0.14em] text-muted-foreground">Pick by situation</h3>
      <ul className="mt-3 grid gap-2 sm:grid-cols-2">
        {c.picks.map((p) => (
          <li key={p.scenario} className="rounded-xl border border-border bg-background/50 p-3 text-sm">
            <p className="flex items-center justify-between gap-2">
              <span className="font-medium">{p.scenario}</span>
              <span className={cn("spec-figure text-xs", p.choice === "either" ? "text-muted-foreground" : "text-primary")}>
                {names[p.choice]}
              </span>
            </p>
            <p className="mt-1 text-muted-foreground">{p.reason}</p>
          </li>
        ))}
      </ul>

      <p className="mt-6 rounded-xl bg-primary/10 px-4 py-3 text-sm text-foreground">
        <span className="font-semibold text-primary">Beginner tip: </span>
        {c.beginnerTip}
      </p>
      <p className="mt-4 text-xs text-muted-foreground">
        Generated by AI from the specs on this page. Double-check anything that matters to you.
      </p>
    </section>
  );
}

function VerdictShell({ children }: { children: React.ReactNode }) {
  return (
    <section className="rounded-3xl border border-dashed border-border-strong p-6 text-sm text-muted-foreground">
      <p className="spec-figure mb-2 flex items-center gap-2 text-[11px] uppercase tracking-[0.18em] text-primary">
        <Sparkles className="size-3.5" /> AI summary
      </p>
      {children}
    </section>
  );
}

export function AiVerdictSkeleton() {
  return (
    <section className="rounded-3xl border border-border bg-card p-6 sm:p-8" aria-busy aria-label="Generating AI summary">
      <p className="spec-figure flex items-center gap-2 text-[11px] uppercase tracking-[0.18em] text-primary">
        <Sparkles className="size-3.5 animate-pulse" /> Reading both spec sheets…
      </p>
      <div className="mt-4 space-y-3">
        <div className="h-6 w-4/5 animate-pulse rounded bg-muted" />
        <div className="h-4 w-3/5 animate-pulse rounded bg-muted" />
        <div className="grid gap-3 pt-4 md:grid-cols-2">
          <div className="h-24 animate-pulse rounded-xl bg-muted" />
          <div className="h-24 animate-pulse rounded-xl bg-muted" />
        </div>
      </div>
    </section>
  );
}
